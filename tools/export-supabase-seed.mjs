#!/usr/bin/env node
// Turns data.js into the SQL that seeds the Supabase database behind
// beer-review-buddy — the one-time cutover that made that database the source
// of truth, and the way to regenerate the seed if it ever has to be replayed.
//
//   node tools/export-supabase-seed.mjs            # SQL to stdout
//   node tools/export-supabase-seed.mjs --out f.sql
//   node tools/export-supabase-seed.mjs --json f.json
//
// The JSON form is the same rows the REST API returns, which is what lets
// `npm run sync` be exercised without reaching the network — see
// tools/roundtrip-supabase.mjs.
//
// This runs one way only. Once the database is the source of truth, data.js is
// its output: re-running this against a stale data.js and applying the result
// would overwrite whatever has been logged in the app since.
import { writeFileSync } from 'node:fs';
import { loadData } from './load-data.mjs';
import { toRows, TABLES } from './supabase-rows.mjs';

const arg = name => {
  const i = process.argv.indexOf(name);
  return i === -1 ? null : process.argv[i + 1];
};

const lit = v => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(lit).join(',')}]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table, rows) {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map(r => `(${cols.map(c => lit(r[c])).join(',')})`).join(',\n');
  return `insert into public.${table} (${cols.join(',')}) values\n${values};\n`;
}

const rows = toRows(loadData());

if (arg('--json')) {
  writeFileSync(arg('--json'), JSON.stringify(rows, null, 2) + '\n');
  process.exit(0);
}

const sql = [
  '-- Generated by tools/export-supabase-seed.mjs in jwal64/JWAL-BEER-REVIEW.',
  '-- Do not hand-edit: it is a snapshot of data.js at the moment the database',
  '-- took over as the source of truth.',
  '',
  // Oldest first, so a delete never trips over a row that still refers to it
  // and a re-run of the seed starts from a clean table rather than doubling it.
  ...[...TABLES].reverse().map(t => `delete from public.${t};`),
  '',
  ...TABLES.map(t => insert(t, rows[t])),
].join('\n');

const out = arg('--out');
if (out) writeFileSync(out, sql);
else process.stdout.write(sql);

if (out) {
  const counts = TABLES.map(t => `${rows[t].length} ${t}`).join(' · ');
  console.log(`Wrote ${out} — ${counts}.`);
}
